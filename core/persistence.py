"""Generic save/load framework — numpy-only, no domain knowledge.

The persistence god-function is decomposed the same way display was: this module
owns only the *generic* slice (params JSON, mesh geometry, face textures, face
metadata) and the stage-iteration loop; every stage serializes/loads its own
arrays via ``Stage.serialize`` / ``Stage.load``.

A ``.npz`` therefore contains:
  * ``params_json``                         — the dataclass params tree
  * ``mesh_vertices`` / ``mesh_face_sizes`` / ``mesh_face_data``  — geometry
  * ``tex_<name>``                          — every non-display face texture
  * ``face_metadata_json``                  — per-face metadata dicts
  * whatever keys each stage's ``serialize`` contributes

A domain layer (``worldgen.globe.serialization``) supplies the params class and a
builder factory; this module stays free of ``worldgen`` imports so the
``worldgen -> core`` dependency edge is never reversed.
"""
from __future__ import annotations

import dataclasses
import json
from pathlib import Path
from typing import Iterable, Tuple, Union

import numpy as np

from core.mesh import PolygonMesh
from core.world import World


class NumpyEncoder(json.JSONEncoder):
    """JSON encoder that degrades numpy scalars/arrays to plain Python."""

    def default(self, obj):
        if isinstance(obj, np.integer):
            return int(obj)
        if isinstance(obj, np.floating):
            return float(obj)
        if isinstance(obj, np.bool_):
            return bool(obj)
        if isinstance(obj, np.ndarray):
            return obj.tolist()
        return super().default(obj)


def deep_from_dict(cls, d: dict):
    """Reconstruct a (possibly nested) ``@dataclass`` from an ``asdict()`` dict.

    When a field's ``default_factory`` returns a dataclass instance, recurse into
    the nested dict so arbitrarily deep param trees round-trip.
    """
    init_kwargs = {}
    for f in dataclasses.fields(cls):
        if f.name not in d:
            continue
        val = d[f.name]
        if isinstance(val, dict) and f.default_factory is not dataclasses.MISSING:
            child_cls = type(f.default_factory())
            if dataclasses.is_dataclass(child_cls):
                val = deep_from_dict(child_cls, val)
        init_kwargs[f.name] = val
    return cls(**init_kwargs)


# ── Mesh (generic geometry + raster layers) ──────────────────────────────────────


def _serialize_mesh(mesh: PolygonMesh, arrays: dict) -> None:
    """Write geometry, non-display face textures, and face metadata into ``arrays``."""
    face_sizes = np.array([len(f) for f in mesh.faces], dtype=np.int32)
    face_data = np.array([v for face in mesh.faces for v in face], dtype=np.int32)
    arrays["mesh_vertices"] = mesh.vertices.astype(np.float32)
    arrays["mesh_face_sizes"] = face_sizes
    arrays["mesh_face_data"] = face_data

    # Skip display-only RGBA textures — they are regenerated by apply_display().
    for name, tex in mesh.face_textures.items():
        if name.endswith("_rgba"):
            continue
        arrays[f"tex_{name}"] = tex

    arrays["face_metadata_json"] = np.array(
        json.dumps(mesh.face_metadata, cls=NumpyEncoder)
    )


def _reconstruct_mesh(data) -> PolygonMesh:
    """Rebuild a ``PolygonMesh`` (geometry + textures + metadata) from npz arrays."""
    face_sizes = data["mesh_face_sizes"].tolist()
    face_data_flat = data["mesh_face_data"].tolist()
    faces: list[tuple[int, ...]] = []
    offset = 0
    for size in face_sizes:
        faces.append(tuple(face_data_flat[offset:offset + size]))
        offset += size
    mesh = PolygonMesh(data["mesh_vertices"], faces)

    for key in data.files:
        if not key.startswith("tex_"):
            continue
        tex = data[key]
        mesh.set_face_textures(key[4:], tex, n_channels=tex.shape[-1])

    for i, meta in enumerate(json.loads(str(data["face_metadata_json"]))):
        mesh.face_metadata[i].update(meta)

    return mesh


# ── Save / load orchestration ────────────────────────────────────────────────────


def save_world(world: World, params, stages: Iterable, path: Union[str, Path]) -> None:
    """Serialize ``world`` (params + mesh + each stage's arrays) to compressed ``.npz``.

    ``stages`` is any iterable of ``Stage`` (typically a ``Pipeline``); each
    contributes its own keyed arrays via ``serialize()``.
    """
    if world is None or world.mesh is None:
        raise RuntimeError("save_world() requires a built world with a mesh")

    arrays: dict[str, np.ndarray] = {}
    arrays["params_json"] = np.array(
        json.dumps(dataclasses.asdict(params), cls=NumpyEncoder)
    )
    _serialize_mesh(world.mesh, arrays)
    for stage in stages:
        arrays.update(stage.serialize())

    np.savez_compressed(path, **arrays)


def load_world(path: Union[str, Path], params_cls) -> Tuple[object, World, object]:
    """Reconstruct ``(params, world, data)`` from a ``.npz``.

    Restores the params dataclass tree and a mesh-bearing ``World``; the caller
    runs each stage's ``load(data, ctx)`` against the returned npz ``data`` to
    rehydrate stage-specific state and re-register features.
    """
    data = np.load(Path(path), allow_pickle=False)
    params = deep_from_dict(params_cls, json.loads(str(data["params_json"])))
    world = World(mesh=_reconstruct_mesh(data))
    return params, world, data
