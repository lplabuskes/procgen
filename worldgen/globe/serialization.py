"""Save and load a fully-built globe.

Thin domain shim over the generic ``core.persistence`` framework: that module
owns the params/mesh/texture/metadata slice and the stage-iteration loop; each
``Stage`` serializes/loads its own arrays. This file only supplies the params
class (``GlobeParams``) and the pipeline (``GlobePipeline``) and runs the
per-stage ``load`` loop, so back-compat array keys live in the stages that own them.

Usage::

    from worldgen.globe.serialization import save_globe, load_globe

    # After GlobePipeline.build(ctx):
    save_globe(pipeline, "worlds/seed42.npz")

    # Later:
    pipeline, globe = load_globe("worlds/seed42.npz")
    pipeline.apply_display(window)
"""
from __future__ import annotations

from pathlib import Path
from typing import Union

from core.persistence import load_world, save_world
from core.pipeline import BuildContext
from worldgen.globe.builder import GlobePipeline, GlobeParams
from core.world import World


def save_globe(pipeline: GlobePipeline, path: Union[str, Path]) -> None:
    """Serialize a fully-built globe to a compressed ``.npz`` file.

    Display textures (``*_rgba``) are skipped — they are regenerated by
    ``apply_display()``. Everything else needed to call ``apply_display()`` and
    interact with the globe is saved.

    Args:
        pipeline: A ``GlobePipeline`` whose ``build()`` has already been called.
        path:     Destination file path (``.npz`` appended by numpy if absent).
    """
    if pipeline.globe is None:
        raise RuntimeError("GlobePipeline.build() must be called before save_globe()")
    save_world(pipeline.globe, pipeline.params, pipeline, path)


def load_globe(path: Union[str, Path]) -> tuple[GlobePipeline, World]:
    """Deserialize a globe saved by ``save_globe()``.

    Reconstructs params + mesh via ``core.persistence``, then runs each stage's
    ``load`` to rehydrate builder state and re-register features.

    Returns:
        ``(pipeline, globe)`` — call ``pipeline.apply_display(window)`` to wire
        the loaded world into a map window.
    """
    params, world, data = load_world(path, GlobeParams)
    pipeline = GlobePipeline(params)
    ctx = BuildContext(world=world)
    for stage in pipeline:
        stage.load(data, ctx)
    pipeline.globe = world
    return pipeline, world
