"""Save and load a fully-built globe.

Thin domain shim over the generic ``core.persistence`` framework: that module
owns the params/mesh/texture/metadata slice and the stage-iteration loop; each
``Stage`` serializes/loads its own arrays. This file only supplies the params
class (``GlobeParams``) and the builder (``GlobeBuilder``) and runs the per-stage
``load`` loop, so back-compat array keys live in the stages that own them.

Usage::

    from worldgen.globe.serialization import save_globe, load_globe

    # After GlobeBuilder.build():
    save_globe(builder, "worlds/seed42.npz")

    # Later:
    builder, globe = load_globe("worlds/seed42.npz")
    builder.apply_display(window)
"""
from __future__ import annotations

from pathlib import Path
from typing import Union

from core.persistence import load_world, save_world
from core.pipeline import BuildContext
from worldgen.globe.builder import GlobeBuilder, GlobeParams
from worldgen.globe.globe import Globe


def save_globe(builder: GlobeBuilder, path: Union[str, Path]) -> None:
    """Serialize a fully-built globe to a compressed ``.npz`` file.

    Display textures (``*_rgba``) are skipped — they are regenerated by
    ``apply_display()``. Everything else needed to call ``apply_display()`` and
    interact with the globe is saved.

    Args:
        builder: A ``GlobeBuilder`` whose ``build()`` has already been called.
        path:    Destination file path (``.npz`` appended by numpy if absent).
    """
    if builder.globe is None:
        raise RuntimeError("GlobeBuilder.build() must be called before save_globe()")
    save_world(builder.globe, builder.params, builder.pipeline, path)


def load_globe(path: Union[str, Path]) -> tuple[GlobeBuilder, Globe]:
    """Deserialize a globe saved by ``save_globe()``.

    Reconstructs params + mesh via ``core.persistence``, then runs each stage's
    ``load`` to rehydrate builder state and re-register features.

    Returns:
        ``(builder, globe)`` — call ``builder.apply_display(window)`` to wire the
        loaded world into a map window.
    """
    params, world, data = load_world(path, GlobeParams)
    builder = GlobeBuilder(params)
    ctx = BuildContext(world=world)
    for stage in builder.pipeline:
        stage.load(data, ctx)
    builder.globe = world
    return builder, world
