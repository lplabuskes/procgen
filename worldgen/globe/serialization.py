"""Save and load a fully-built globe.

Usage::

    from worldgen.globe.serialization import save_globe, load_globe

    # After GlobeBuilder.build():
    save_globe(builder, "worlds/seed42.npz")

    # Later:
    builder, globe = load_globe("worlds/seed42.npz")
    builder.apply_display(window)
"""
from __future__ import annotations

import dataclasses
import json
from pathlib import Path
from typing import Union

import numpy as np

from worldgen.climate.currents import CurrentsResult
from worldgen.globe.builder import GlobeBuilder, GlobeParams
from worldgen.globe.globe import Globe
from core.mesh import PolygonMesh


class _NumpyEncoder(json.JSONEncoder):
    def default(self, obj):
        if isinstance(obj, np.integer):
            return int(obj)
        if isinstance(obj, np.floating):
            return float(obj)
        if isinstance(obj, np.bool_):
            return bool(obj)
        if isinstance(obj, np.ndarray):
            return obj.tolist()
        return super().default(obj)


def _deep_from_dict(cls, d: dict):
    """Reconstruct a @dataclass from an asdict() output dict.

    Handles arbitrary nesting: when a field's default_factory returns a
    dataclass instance, recurse into the nested dict.
    """
    init_kwargs = {}
    for f in dataclasses.fields(cls):
        if f.name not in d:
            continue
        val = d[f.name]
        if isinstance(val, dict) and f.default_factory is not dataclasses.MISSING:
            child_cls = type(f.default_factory())
            if dataclasses.is_dataclass(child_cls):
                val = _deep_from_dict(child_cls, val)
        init_kwargs[f.name] = val
    return cls(**init_kwargs)


def save_globe(builder: GlobeBuilder, path: Union[str, Path]) -> None:
    """Serialize a fully-built globe to a compressed .npz file.

    Skips display textures (``*_rgba``) — they are regenerated by
    ``apply_display()``.  Everything else needed to call ``apply_display()``
    and interact with the globe is saved.

    Args:
        builder: A ``GlobeBuilder`` whose ``build()`` has already been called.
        path:    Destination file path.  A ``.npz`` extension is appended by
                 numpy if not already present.
    """
    globe = builder.globe
    if globe is None:
        raise RuntimeError("GlobeBuilder.build() must be called before save_globe()")

    eb = builder.elevation_builder
    cb = builder.climate_builder
    hb = builder.hydrology_builder
    rb = builder.resources_builder
    mesh = eb.mesh

    arrays: dict[str, np.ndarray] = {}

    # ── Params ──────────────────────────────────────────────────────────────
    arrays["params_json"] = np.array(
        json.dumps(dataclasses.asdict(builder.params), cls=_NumpyEncoder)
    )

    # ── Mesh geometry ────────────────────────────────────────────────────────
    face_sizes = np.array([len(f) for f in mesh.faces], dtype=np.int32)
    face_data = np.array([v for face in mesh.faces for v in face], dtype=np.int32)
    arrays["mesh_vertices"] = mesh.vertices.astype(np.float32)
    arrays["mesh_face_sizes"] = face_sizes
    arrays["mesh_face_data"] = face_data

    # ── Face textures (skip display-only *_rgba) ──────────────────────────
    for name, tex in mesh.face_textures.items():
        if name.endswith("_rgba"):
            continue
        arrays[f"tex_{name}"] = tex

    # ── Face metadata ─────────────────────────────────────────────────────
    arrays["face_metadata_json"] = np.array(
        json.dumps(mesh.face_metadata, cls=_NumpyEncoder)
    )

    # ── ElevationBuilder attributes ───────────────────────────────────────
    arrays["eb_plate_ids"] = np.array(eb.plate_ids, dtype=np.int32)
    arrays["eb_plate_omegas"] = eb.plate_omegas.astype(np.float64)
    arrays["eb_face_velocities"] = eb.face_velocities.astype(np.float64)
    arrays["eb_volcanism"] = eb.volcanism.astype(np.float64)
    arrays["eb_elevations"] = eb.elevations.astype(np.float64)
    arrays["eb_max_speed"] = np.array([eb.max_speed], dtype=np.float64)
    if eb.volcano_positions is not None and len(eb.volcano_positions) > 0:
        arrays["eb_volcano_positions"] = eb.volcano_positions.astype(np.float32)

    # ── ClimateBuilder attributes ─────────────────────────────────────────
    if cb.winds is not None:
        arrays["cb_winds"] = cb.winds.astype(np.float32)

    if cb.currents is not None:
        arrays["cb_currents_vectors"] = cb.currents.currents.astype(np.float32)
        arrays["cb_currents_streamfunction"] = cb.currents.streamfunction.astype(np.float32)
        arrays["cb_currents_temp_delta"] = cb.currents.temperature_delta.astype(np.float32)
        arrays["cb_currents_precip_delta"] = cb.currents.precipitation_delta.astype(np.float32)
        arrays["cb_currents_advected_insolation"] = cb.currents.advected_insolation.astype(np.float32)

    # ── HydrologyBuilder: rivers (positions/flows/in_lake per river) ──────
    if hb.rivers and globe.has_feature("rivers"):
        paths = globe.get_feature("rivers")
        all_pos, all_flows, all_in_lake = [], [], []
        pos_offsets, flow_offsets = [0], [0]
        for positions, flows, in_lake in paths:
            all_pos.append(positions)
            all_flows.append(flows)
            all_in_lake.append(in_lake)
            pos_offsets.append(pos_offsets[-1] + len(positions))
            flow_offsets.append(flow_offsets[-1] + len(flows))
        arrays["river_positions_flat"] = np.concatenate(all_pos).astype(np.float32)
        arrays["river_flows_flat"] = np.concatenate(all_flows).astype(np.float32)
        arrays["river_in_lake_flat"] = np.concatenate(all_in_lake).astype(np.bool_)
        arrays["river_pos_offsets"] = np.array(pos_offsets, dtype=np.int64)
        arrays["river_flow_offsets"] = np.array(flow_offsets, dtype=np.int64)

    if hb.lake_polygons:
        all_verts, lake_offsets = [], [0]
        for poly in hb.lake_polygons:
            all_verts.append(poly)
            lake_offsets.append(lake_offsets[-1] + len(poly))
        arrays["lake_polys_flat"] = np.concatenate(all_verts).astype(np.float32)
        arrays["lake_poly_offsets"] = np.array(lake_offsets, dtype=np.int64)

    if hb.delta_positions is not None and len(hb.delta_positions) > 0:
        arrays["hb_delta_positions"] = hb.delta_positions.astype(np.float32)

    # ── ResourcesBuilder: minerals and rare bio ───────────────────────────
    if rb.minerals is not None and len(rb.minerals[0]) > 0:
        m_pos, m_kinds, m_abund = rb.minerals
        arrays["mineral_positions"] = m_pos.astype(np.float32)
        arrays["mineral_kinds"] = m_kinds.astype(np.int8)
        arrays["mineral_abundances"] = m_abund.astype(np.float32)

    if rb.rare_bio is not None and len(rb.rare_bio[0]) > 0:
        rb_pos, rb_kinds, rb_abund = rb.rare_bio
        arrays["rare_bio_positions"] = rb_pos.astype(np.float32)
        arrays["rare_bio_kinds"] = rb_kinds.astype(np.int8)
        arrays["rare_bio_abundances"] = rb_abund.astype(np.float32)

    # ── CostBuilder: base cost surfaces ────────────────────────────────────
    cs = builder.cost_builder.surfaces
    if cs is not None:
        arrays["cost_land_base_cost"] = cs.land_base_cost.astype(np.float32)
        arrays["cost_land_passable"] = cs.land_passable.astype(np.bool_)
        arrays["cost_river_flow_dir"] = cs.river_flow_dir.astype(np.float32)
        arrays["cost_river_flow_mag"] = cs.river_flow_mag.astype(np.float32)
        arrays["cost_river_navigability"] = cs.river_navigability.astype(np.float32)
        arrays["cost_sea_base_cost"] = cs.sea_base_cost.astype(np.float32)
        arrays["cost_sea_passable"] = cs.sea_passable.astype(np.bool_)
        arrays["cost_strait_mask"] = cs.strait_mask.astype(np.bool_)

    np.savez_compressed(path, **arrays)


def load_globe(path: Union[str, Path]) -> tuple[GlobeBuilder, Globe]:
    """Deserialize a globe saved by ``save_globe()``.

    Reconstructs the mesh from saved geometry (no dependency on the mesh
    cache), restores all face textures and metadata, and re-wires all builder
    attributes needed by ``apply_display()``.

    Returns:
        ``(builder, globe)`` — call ``builder.apply_display(window)`` to wire
        the loaded world into a map window.
    """
    path = Path(path)
    data = np.load(path, allow_pickle=False)

    # ── Params ───────────────────────────────────────────────────────────────
    params_dict = json.loads(str(data["params_json"]))
    params = _deep_from_dict(GlobeParams, params_dict)

    # ── Mesh geometry ─────────────────────────────────────────────────────
    face_sizes = data["mesh_face_sizes"].tolist()
    face_data_flat = data["mesh_face_data"].tolist()
    faces: list[tuple[int, ...]] = []
    offset = 0
    for size in face_sizes:
        faces.append(tuple(face_data_flat[offset:offset + size]))
        offset += size
    mesh = PolygonMesh(data["mesh_vertices"], faces)

    # ── Face textures ──────────────────────────────────────────────────────
    for key in data.files:
        if not key.startswith("tex_"):
            continue
        name = key[4:]
        tex = data[key]
        mesh.set_face_textures(name, tex, n_channels=tex.shape[-1])

    # ── Face metadata ──────────────────────────────────────────────────────
    saved_meta = json.loads(str(data["face_metadata_json"]))
    for i, meta in enumerate(saved_meta):
        mesh.face_metadata[i].update(meta)

    # ── Build GlobeBuilder and hydrate ────────────────────────────────────
    builder = GlobeBuilder(params)
    eb = builder.elevation_builder
    cb = builder.climate_builder
    hb = builder.hydrology_builder
    rb = builder.resources_builder

    eb.mesh = mesh
    eb.plate_ids = data["eb_plate_ids"].tolist()
    eb.plate_omegas = data["eb_plate_omegas"]
    eb.face_velocities = data["eb_face_velocities"]
    eb.volcanism = data["eb_volcanism"]
    eb.elevations = data["eb_elevations"]
    eb.max_speed = float(data["eb_max_speed"][0])
    if "eb_volcano_positions" in data.files:
        eb.volcano_positions = data["eb_volcano_positions"]

    if "cb_winds" in data.files:
        cb.winds = data["cb_winds"]

    if "cb_currents_vectors" in data.files:
        cb.currents = CurrentsResult(
            currents=data["cb_currents_vectors"],
            streamfunction=data["cb_currents_streamfunction"],
            temperature_delta=data["cb_currents_temp_delta"],
            precipitation_delta=data["cb_currents_precip_delta"],
            advected_insolation=data["cb_currents_advected_insolation"],
        )

    # ── Rivers ────────────────────────────────────────────────────────────
    paths_with_flow: list[tuple] = []
    if "river_pos_offsets" in data.files:
        pos_flat = data["river_positions_flat"]
        flows_flat = data["river_flows_flat"]
        in_lake_flat = data["river_in_lake_flat"]
        pos_offs = data["river_pos_offsets"]
        flow_offs = data["river_flow_offsets"]
        for i in range(len(pos_offs) - 1):
            paths_with_flow.append((
                pos_flat[pos_offs[i]:pos_offs[i + 1]],
                flows_flat[flow_offs[i]:flow_offs[i + 1]],
                in_lake_flat[flow_offs[i]:flow_offs[i + 1]],
            ))
        hb.rivers = paths_with_flow

    lake_polygons: list[np.ndarray] = []
    if "lake_poly_offsets" in data.files:
        poly_flat = data["lake_polys_flat"]
        poly_offs = data["lake_poly_offsets"]
        lake_polygons = [
            poly_flat[poly_offs[i]:poly_offs[i + 1]]
            for i in range(len(poly_offs) - 1)
        ]
        hb.lake_polygons = lake_polygons

    if "hb_delta_positions" in data.files:
        hb.delta_positions = data["hb_delta_positions"]

    # ── Resources ─────────────────────────────────────────────────────────
    if "mineral_positions" in data.files:
        rb.minerals = (
            data["mineral_positions"],
            data["mineral_kinds"],
            data["mineral_abundances"],
        )

    if "rare_bio_positions" in data.files:
        rb.rare_bio = (
            data["rare_bio_positions"],
            data["rare_bio_kinds"],
            data["rare_bio_abundances"],
        )

    # ── Globe features ────────────────────────────────────────────────────
    globe = Globe(mesh=mesh)

    if paths_with_flow:
        globe.add_feature("rivers", paths_with_flow)

    if lake_polygons:
        globe.add_feature("lakes", lake_polygons)

    if "hb_delta_positions" in data.files:
        globe.add_feature("deltas", hb.delta_positions)

    if "eb_volcano_positions" in data.files:
        globe.add_feature("volcanoes", eb.volcano_positions)

    if "mineral_positions" in data.files:
        globe.add_feature("minerals", rb.minerals)

    if "rare_bio_positions" in data.files:
        globe.add_feature("rare_bio", rb.rare_bio)

    if "cost_land_base_cost" in data.files:
        from worldgen.cost.surfaces import CostSurfaces

        river_flow_mag = data["cost_river_flow_mag"]
        # Back-compat: navigability was added later; default to zeros.
        river_navigability = (
            data["cost_river_navigability"]
            if "cost_river_navigability" in data.files
            else np.zeros_like(river_flow_mag)
        )
        cost_surfaces = CostSurfaces(
            land_base_cost=data["cost_land_base_cost"],
            land_passable=data["cost_land_passable"],
            river_flow_dir=data["cost_river_flow_dir"],
            river_flow_mag=river_flow_mag,
            river_navigability=river_navigability,
            sea_base_cost=data["cost_sea_base_cost"],
            sea_passable=data["cost_sea_passable"],
            strait_mask=data["cost_strait_mask"],
        )
        builder.cost_builder.surfaces = cost_surfaces
        globe.add_feature("cost_surfaces", cost_surfaces)

    if cb.winds is not None:
        centroids = mesh.face_centroids.astype(np.float32)
        winds_feature = [
            (centroids.copy(), cb.winds[:, season_idx, :].astype(np.float32))
            for season_idx in range(cb.winds.shape[1])
        ]
        globe.add_feature("winds", winds_feature)

    if cb.currents is not None:
        centroids = mesh.face_centroids.astype(np.float32)
        globe.add_feature(
            "currents",
            [(
                centroids.copy(),
                cb.currents.currents.astype(np.float32),
                cb.currents.temperature_delta.astype(np.float32),
            )],
        )

    builder.globe = globe
    return builder, globe
